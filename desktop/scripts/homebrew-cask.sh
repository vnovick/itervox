#!/usr/bin/env bash
# The Homebrew cask of the Mac app (#244): Casks/itervox-app.rb in the tap
# that also holds the CLI formula (.goreleaser.yaml `brews`), so that
#   brew install --cask vnovick/tap/itervox-app
# installs the signed, notarized app from the GitHub release. The cask has
# its own token: `itervox` is the CLI formula, so a plain
# `brew install vnovick/tap/itervox` keeps meaning the command-line tool.
#
# Subcommands:
#   render --version X.Y.Z (--dmg <file> | --sha256 <hex>)
#          [--repo owner/name] [--conf tauri.macos.conf.json] [--out <file>]
#       Write the cask: the version, the DMG's SHA-256 (computed from --dmg),
#       the DMG's release URL, the minimum macOS from the app's
#       bundle.macOS.minimumSystemVersion, and auto_updates (the app updates
#       itself). Prints to stdout unless --out is given. Needs jq.
#   publish --cask <file> --version X.Y.Z --notarized <true|false>
#          [--tap owner/homebrew-tap]
#       Commit the cask to the tap through the GitHub API (gh), with the
#       token in HOMEBREW_TAP_GITHUB_TOKEN. Skips, successfully and with a
#       notice, when the release was not notarized (no signing secrets: an
#       unsigned app must never reach the tap), when the token is not set,
#       or for a pre-release version.
#
# The token is only ever passed to gh in its environment; it is never
# printed or put on a command line.
set -euo pipefail
set +x

# The cask's token, and so its file in the tap (Casks/<token>.rb).
token="itervox-app"

die() {
  echo "homebrew-cask: $*" >&2
  exit 1
}

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
semver='^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z.-]+)?$'

# The `depends_on macos:` symbol of a minimumSystemVersion.
macos_symbol() {
  case "${1%%.*}" in
    11) echo big_sur ;;
    12) echo monterey ;;
    13) echo ventura ;;
    14) echo sonoma ;;
    15) echo sequoia ;;
    26) echo tahoe ;;
    *) die "minimumSystemVersion '$1' has no Homebrew macOS name in this script; add it" ;;
  esac
}

sha256_of() {
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  elif command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  else
    die "neither shasum nor sha256sum is installed"
  fi
}

cmd_render() {
  local version="" dmg="" sha="" repo="vnovick/itervox" out=""
  local conf="$script_dir/../src-tauri/tauri.macos.conf.json"
  while [ "$#" -gt 0 ]; do
    case "$1" in
      --version) version="${2-}"; shift 2 ;;
      --dmg) dmg="${2-}"; shift 2 ;;
      --sha256) sha="${2-}"; shift 2 ;;
      --repo) repo="${2-}"; shift 2 ;;
      --conf) conf="${2-}"; shift 2 ;;
      --out) out="${2-}"; shift 2 ;;
      *) die "unknown argument $1" ;;
    esac
  done
  command -v jq >/dev/null 2>&1 || die "jq is required"
  version="${version#v}"
  [[ "$version" =~ $semver ]] || die "--version '$version' is not MAJOR.MINOR.PATCH[-PRERELEASE]"
  if [ -n "$dmg" ]; then
    [ -n "$sha" ] && die "give --dmg or --sha256, not both"
    [ -s "$dmg" ] || die "--dmg $dmg is missing or empty"
    sha="$(sha256_of "$dmg")"
  fi
  [[ "$sha" =~ ^[0-9a-f]{64}$ ]] || die "--sha256 must be 64 lowercase hex digits (or give --dmg)"
  [[ "$repo" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || die "--repo '$repo' is not owner/name"
  [ -f "$conf" ] || die "--conf $conf does not exist"
  local min
  min="$(jq -r '.bundle.macOS.minimumSystemVersion // ""' "$conf")"
  [ -n "$min" ] || die "$conf has no bundle.macOS.minimumSystemVersion"
  local symbol
  symbol="$(macos_symbol "$min")"

  # The DMG name is the one desktop-release.yml uploads for a signed build.
  local cask
  cask="$(cat <<EOF
# Generated by desktop/scripts/homebrew-cask.sh in $repo (#244).
# The desktop release workflow rewrites this file after each notarized
# release; edit the script, not this file.
cask "$token" do
  version "$version"
  sha256 "$sha"

  url "https://github.com/$repo/releases/download/v#{version}/Itervox_#{version}_universal.dmg"
  name "Itervox"
  desc "Menu bar app for local and remote agent daemons"
  homepage "https://github.com/$repo"

  livecheck do
    url :url
    strategy :github_latest
  end

  auto_updates true
  depends_on macos: ">= :$symbol"

  app "Itervox.app"

  caveats <<~EOS
    Itervox.app includes its own itervox daemon. For the itervox command,
    use the app's "Install Command-Line Tool..." menu item, or install the
    CLI formula with: brew install vnovick/tap/itervox
    Keep only one itervox on your PATH.
  EOS

  zap trash: [
    "~/Library/Application Support/dev.itervox.desktop",
    "~/Library/Caches/dev.itervox.desktop",
    "~/Library/Logs/dev.itervox.desktop",
    "~/Library/WebKit/dev.itervox.desktop",
  ]
end
EOF
)"
  if [ -n "$out" ]; then
    printf '%s\n' "$cask" >"$out"
    echo "homebrew-cask: wrote $out (version $version)" >&2
  else
    printf '%s\n' "$cask"
  fi
}

cmd_publish() {
  local cask="" version="" notarized="" tap="vnovick/homebrew-tap"
  while [ "$#" -gt 0 ]; do
    case "$1" in
      --cask) cask="${2-}"; shift 2 ;;
      --version) version="${2-}"; shift 2 ;;
      --notarized) notarized="${2-}"; shift 2 ;;
      --tap) tap="${2-}"; shift 2 ;;
      *) die "unknown argument $1" ;;
    esac
  done
  version="${version#v}"
  if [ "$notarized" != "true" ]; then
    echo "::notice title=Homebrew cask skipped::the app was not signed and notarized (signing secrets are not available), so the tap is not updated."
    return 0
  fi
  if [ -z "${HOMEBREW_TAP_GITHUB_TOKEN-}" ]; then
    echo "::warning title=Homebrew cask skipped::HOMEBREW_TAP_GITHUB_TOKEN is not set, so Casks/$token.rb in $tap is not updated."
    return 0
  fi
  [[ "$version" =~ $semver ]] || die "--version '$version' is not MAJOR.MINOR.PATCH[-PRERELEASE]"
  if [[ "$version" == *-* ]]; then
    echo "::notice title=Homebrew cask skipped::$version is a pre-release; the cask follows stable releases only."
    return 0
  fi
  [ -s "$cask" ] || die "--cask $cask is missing or empty"
  grep -q "^  version \"$version\"$" "$cask" || die "$cask is not the cask of $version"
  [[ "$tap" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]] || die "--tap '$tap' is not owner/name"
  command -v gh >/dev/null 2>&1 || die "gh is required"

  local api="repos/$tap/contents/Casks/$token.rb" sha content
  # The current file's blob sha (none for the first release).
  sha="$(GH_TOKEN="$HOMEBREW_TAP_GITHUB_TOKEN" gh api "$api" --jq .sha 2>/dev/null || true)"
  content="$(base64 <"$cask" | tr -d '\n')"
  local args=(api -X PUT "$api" -f "message=$token $version (cask)" -f "content=$content")
  [ -z "$sha" ] || args+=(-f "sha=$sha")
  GH_TOKEN="$HOMEBREW_TAP_GITHUB_TOKEN" gh "${args[@]}" --silent \
    || die "could not update Casks/$token.rb in $tap"
  echo "homebrew-cask: updated Casks/$token.rb in $tap to $version"
}

sub="${1-}"
[ "$#" -gt 0 ] && shift
case "$sub" in
  render) cmd_render "$@" ;;
  publish) cmd_publish "$@" ;;
  *) die "usage: homebrew-cask.sh render|publish …" ;;
esac
